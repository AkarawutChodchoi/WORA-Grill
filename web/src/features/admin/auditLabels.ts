/** Short, readable summary of an audit entry's data (falls back to compact JSON). */
export function auditSummary(data: Record<string, unknown> | null): string {
  if (!data) return '';
  const d = data as Record<string, any>;
  const parts: string[] = [];
  if (Array.isArray(d.items)) parts.push(d.items.map((i: any) => `${i.name ?? ''}${i.qty ? ` ×${i.qty}` : ''}`).join(', '));
  if (d.name) parts.push(String(d.name));
  if (d.orderNo) parts.push(`บิล #${d.orderNo}`);
  if (d.guestCount) parts.push(`${d.guestCount} คน`);
  if (typeof d.created === 'number') parts.push(`เพิ่ม ${d.created} รายการ`);
  return parts.filter(Boolean).join(' · ');
}
