import { sql } from 'drizzle-orm';
import { boolean, date, index, integer, jsonb, pgTable, primaryKey, text, unique, uniqueIndex, uuid } from 'drizzle-orm/pg-core';
import { createdAt, pk, ts, updatedAt } from './_common';
import { branches, organizations, users } from './core';
import { diningTables } from './tables';

export const ORDER_STATUS_VALUES = ['OPEN', 'BILL_REQUESTED', 'PAID', 'CLOSED', 'VOIDED'] as const;

/** Bills. Monetary totals are integer satang snapshots recomputed whenever lines change. */
export const orders = pgTable(
  'orders',
  {
    id: pk(),
    organizationId: uuid('organization_id').notNull().references(() => organizations.id),
    branchId: uuid('branch_id').notNull().references(() => branches.id),
    orderNo: text('order_no').notNull(),
    businessDate: date('business_date').notNull(),
    channel: text('channel').notNull(),
    source: text('source', { enum: ['POS', 'WAITER', 'QR', 'KIOSK', 'DELIVERY_API'] }).notNull().default('POS'),
    tableId: uuid('table_id').references(() => diningTables.id),
    guestCount: integer('guest_count').notNull().default(1),
    customerId: uuid('customer_id'),
    status: text('status', { enum: ORDER_STATUS_VALUES }).notNull().default('OPEN'),
    subtotalSatang: integer('subtotal_satang').notNull().default(0),
    discountSatang: integer('discount_satang').notNull().default(0),
    serviceChargeSatang: integer('service_charge_satang').notNull().default(0),
    vatSatang: integer('vat_satang').notNull().default(0),
    grandTotalSatang: integer('grand_total_satang').notNull().default(0),
    paidSatang: integer('paid_satang').notNull().default(0),
    /** Tax/service configuration in force when the bill was opened (snapshot). */
    pricing: jsonb('pricing').$type<{ vatMode: string; vatBps: number; serviceChargeBps: number; serviceChargeTaxable: boolean }>().notNull(),
    note: text('note'),
    customerName: text('customer_name'),
    customerPhone: text('customer_phone'),
    externalRef: text('external_ref'),
    mergedIntoOrderId: uuid('merged_into_order_id'),
    shiftId: uuid('shift_id'),
    openedBy: uuid('opened_by').references(() => users.id),
    closedBy: uuid('closed_by').references(() => users.id),
    voidedBy: uuid('voided_by').references(() => users.id),
    voidReason: text('void_reason'),
    openedAt: ts('opened_at').notNull().defaultNow(),
    billRequestedAt: ts('bill_requested_at'),
    paidAt: ts('paid_at'),
    closedAt: ts('closed_at'),
    voidedAt: ts('voided_at'),
    version: integer('version').notNull().default(0),
    createdAt: createdAt(),
    updatedAt: updatedAt(),
  },
  (t) => [
    unique('orders_branch_no_uq').on(t.branchId, t.businessDate, t.orderNo),
    index('orders_branch_status_idx').on(t.branchId, t.status),
    index('orders_branch_date_idx').on(t.branchId, t.businessDate),
    // At most one active bill per table (SPEC: prevent two dine-in orders claiming the same table).
    uniqueIndex('orders_active_table_uq').on(t.tableId).where(sql`status in ('OPEN','BILL_REQUESTED') and table_id is not null`),
  ],
);

/** Per-branch, per-business-day running bill number. */
export const orderCounters = pgTable(
  'order_counters',
  {
    branchId: uuid('branch_id').notNull().references(() => branches.id),
    businessDate: date('business_date').notNull(),
    lastNo: integer('last_no').notNull().default(0),
  },
  (t) => [primaryKey({ columns: [t.branchId, t.businessDate] })],
);

export const ITEM_STATUS_VALUES = ['PENDING', 'SENT', 'PREPARING', 'READY', 'SERVED', 'CANCELLED'] as const;

export interface ModifierSnapshot {
  modifierId: string;
  groupName: string;
  name: string;
  qty: number;
  priceDeltaSatang: number;
}

/**
 * Bill lines. Name, prices, modifiers, allergens and routing are snapshots taken when the line is
 * added, so later menu edits never rewrite history (SPEC §5). The id may be generated by the client
 * so that retries are idempotent.
 */
export const orderItems = pgTable(
  'order_items',
  {
    id: uuid('id').primaryKey(),
    orderId: uuid('order_id').notNull().references(() => orders.id),
    organizationId: uuid('organization_id').notNull().references(() => organizations.id),
    branchId: uuid('branch_id').notNull().references(() => branches.id),
    menuItemId: uuid('menu_item_id').notNull(),
    nameSnapshot: text('name_snapshot').notNull(),
    nameEnSnapshot: text('name_en_snapshot'),
    basePriceSatang: integer('base_price_satang').notNull(),
    unitPriceSatang: integer('unit_price_satang').notNull(),
    qty: integer('qty').notNull(),
    modifiers: jsonb('modifiers').$type<ModifierSnapshot[]>().notNull().default([]),
    comboComponents: jsonb('combo_components').$type<{ itemId: string; name: string; qty: number }[]>().notNull().default([]),
    allergens: text('allergens').array().notNull().default([]),
    note: text('note'),
    stationCode: text('station_code'),
    course: integer('course').notNull().default(1),
    /** Held course: saved but not fired to the kitchen until released (Hold/Fire). */
    held: boolean('held').notNull().default(false),
    status: text('status', { enum: ITEM_STATUS_VALUES }).notNull().default('PENDING'),
    discountSatang: integer('discount_satang').notNull().default(0),
    lineTotalSatang: integer('line_total_satang').notNull(),
    seq: integer('seq').notNull().default(0),
    source: text('source').notNull().default('POS'),
    createdBy: uuid('created_by').references(() => users.id),
    sentAt: ts('sent_at'),
    preparingAt: ts('preparing_at'),
    readyAt: ts('ready_at'),
    servedAt: ts('served_at'),
    cancelledAt: ts('cancelled_at'),
    cancelledReason: text('cancelled_reason'),
    cancelledBy: uuid('cancelled_by').references(() => users.id),
    createdAt: createdAt(),
  },
  (t) => [
    index('order_items_order_idx').on(t.orderId),
    index('order_items_branch_status_idx').on(t.branchId, t.status),
    index('order_items_menu_idx').on(t.menuItemId),
  ],
);
